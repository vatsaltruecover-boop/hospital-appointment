// Authentication & Role Management Service
// Roles: 'super_admin' (Full control, create clinics, generate doctor creds),
//        'doctor' (Restricted to single assigned clinic, cannot add clinics),
//        'guest' (Patient booking and live TV access)

import { clinicStore } from './store.js';

const AUTH_STORAGE_KEY = 'clinic_auth_session_v2';
const AUTH_CHANNEL_NAME = 'clinic_auth_sync';

export const SUPER_ADMIN_CREDENTIALS = {
  username: 'admin@medipulse.io',
  password: 'admin123',
  name: 'Global System Administrator',
  role: 'super_admin'
};

class AuthService {
  constructor() {
    this.session = this.loadSession();
    this.listeners = new Set();
    this.channel = null;

    if (typeof window !== 'undefined') {
      try {
        this.channel = new BroadcastChannel(AUTH_CHANNEL_NAME);
        this.channel.onmessage = (event) => {
          if (event.data && event.data.type === 'AUTH_CHANGED') {
            this.session = this.loadSession();
            this.notify();
          }
        };
      } catch (e) {
        // BroadcastChannel fallback
      }

      window.addEventListener('storage', (e) => {
        if (e.key === AUTH_STORAGE_KEY) {
          this.session = this.loadSession();
          this.notify();
        }
      });
    }
  }

  loadSession() {
    try {
      if (typeof localStorage !== 'undefined') {
        const data = localStorage.getItem(AUTH_STORAGE_KEY);
        if (data) {
          return JSON.parse(data);
        }
      }
    } catch (e) {
      console.warn('Error reading auth session:', e);
    }
    // Default session: Super admin for immediate seamless evaluation, or guest
    const defaultSession = {
      role: 'super_admin',
      username: SUPER_ADMIN_CREDENTIALS.username,
      name: SUPER_ADMIN_CREDENTIALS.name
    };
    this.saveSession(defaultSession);
    return defaultSession;
  }

  saveSession(session) {
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(session));
      }
    } catch (e) {
      console.error('Error saving auth session:', e);
    }
  }

  commitAuth(session) {
    this.session = session;
    this.saveSession(session);
    if (this.channel) {
      this.channel.postMessage({ type: 'AUTH_CHANGED', session });
    }
    this.notify();
  }

  subscribe(callback) {
    this.listeners.add(callback);
    return () => this.listeners.delete(callback);
  }

  notify() {
    this.listeners.forEach((cb) => {
      try {
        cb(this.session);
      } catch (err) {
        console.error('Auth listener error:', err);
      }
    });
  }

  getSession() {
    return this.session;
  }

  isSuperAdmin() {
    return this.session && this.session.role === 'super_admin';
  }

  isDoctor() {
    return this.session && this.session.role === 'doctor';
  }

  getDoctorClinicId() {
    return this.isDoctor() ? this.session.clinicId : null;
  }

  loginSuperAdmin(username, password) {
    const cleanUser = (username || '').trim().toLowerCase();
    const cleanPass = (password || '').trim();

    if (cleanUser === SUPER_ADMIN_CREDENTIALS.username.toLowerCase() && cleanPass === SUPER_ADMIN_CREDENTIALS.password) {
      const session = {
        role: 'super_admin',
        username: SUPER_ADMIN_CREDENTIALS.username,
        name: SUPER_ADMIN_CREDENTIALS.name,
        loginAt: Date.now()
      };
      this.commitAuth(session);
      return { success: true, session };
    }

    throw new Error('Invalid Super Admin credentials. Hint: admin@medipulse.io / admin123');
  }

  loginDoctor(username, password) {
    const cleanUser = (username || '').trim().toLowerCase();
    const cleanPass = (password || '').trim();

    const allClinics = clinicStore.getAllClinics();
    const matchedClinic = allClinics.find(c => {
      if (!c.doctorCreds) return false;
      const docUser = (c.doctorCreds.username || '').toLowerCase();
      const docPass = c.doctorCreds.password || '';
      return docUser === cleanUser && docPass === cleanPass;
    });

    if (matchedClinic) {
      const session = {
        role: 'doctor',
        clinicId: matchedClinic.id,
        clinicSlug: matchedClinic.slug,
        clinicName: matchedClinic.name,
        doctorName: matchedClinic.doctorName,
        username: matchedClinic.doctorCreds.username,
        loginAt: Date.now()
      };
      this.commitAuth(session);
      clinicStore.setCurrentClinic(matchedClinic.id);
      return { success: true, clinic: matchedClinic, session };
    }

    throw new Error('Invalid doctor username or password. Please verify credentials generated by your Super Admin.');
  }

  loginAsDoctorClinic(clinicId) {
    const clinic = clinicStore.getAllClinics().find(c => c.id === clinicId);
    if (!clinic) throw new Error('Clinic not found.');

    const session = {
      role: 'doctor',
      clinicId: clinic.id,
      clinicSlug: clinic.slug,
      clinicName: clinic.name,
      doctorName: clinic.doctorName,
      username: clinic.doctorCreds ? clinic.doctorCreds.username : `dr.${clinic.slug}@medipulse.io`,
      loginAt: Date.now()
    };
    this.commitAuth(session);
    clinicStore.setCurrentClinic(clinic.id);
    return session;
  }

  logout() {
    const guestSession = { role: 'guest' };
    this.commitAuth(guestSession);
  }
}

export const authService = new AuthService();
